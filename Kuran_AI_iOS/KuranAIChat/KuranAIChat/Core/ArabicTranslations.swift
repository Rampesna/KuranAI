    static func resolve(tr: String, fallback: String) -> String {
        if let value = values[tr] {
            return value
        }

        if tr.hasPrefix("Parolasız giriş etkin ("),
           let open = tr.firstIndex(of: "("),
           let close = tr.lastIndex(of: ")") {
            return "تسجيل الدخول دون كلمة مرور مفعّل \(tr[open...close])"
        }

        if tr.hasPrefix("%"), tr.hasSuffix(" tasarruf") {
            let percent = tr.dropFirst().dropLast(" tasarruf".count)
            return "وفّر \(percent)٪"
        }

        if tr.contains(" Saat ") || tr.contains(" dk ") || tr.hasSuffix(" sn") {
            return tr
                .replacingOccurrences(of: " Saat ", with: " س ")
                .replacingOccurrences(of: " dk", with: " د")
                .replacingOccurrences(of: " sn", with: " ث")
        }

        for name in ["Fatiha", "Bakara", "Rahman", "Hadid", "İhlas"] {
            if tr.hasPrefix("\(name) "), let translated = values[name] {
                return tr.replacingOccurrences(of: name, with: translated)
            }
        }

        return fallback
    }
